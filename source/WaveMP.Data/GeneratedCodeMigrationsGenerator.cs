using Microsoft.EntityFrameworkCore.Migrations.Design;
using Microsoft.EntityFrameworkCore.Migrations.Operations;

namespace WaveMP.Data;

/// <summary>
/// Marks every new migration file as generated code, as EF Core already does for the designer and snapshot files.
/// Analyzers and <c>dotnet format</c> skip generated code, so migrations are never reformatted by hand.
/// </summary>
internal sealed class GeneratedCodeMigrationsGenerator(
    MigrationsCodeGeneratorDependencies dependencies,
    CSharpMigrationsGeneratorDependencies csharpDependencies)
    : CSharpMigrationsGenerator(dependencies, csharpDependencies)
{
    internal const string AutoGeneratedHeader = "// <auto-generated />";

    public override string GenerateMigration(
        string? migrationNamespace,
        string migrationName,
        IReadOnlyList<MigrationOperation> upOperations,
        IReadOnlyList<MigrationOperation> downOperations)
    {
        string code = base.GenerateMigration(migrationNamespace, migrationName, upOperations, downOperations);

        return code.StartsWith(AutoGeneratedHeader, StringComparison.Ordinal)
            ? code
            : AutoGeneratedHeader + Environment.NewLine + code;
    }
}
