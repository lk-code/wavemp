using AwesomeAssertions;

namespace WaveMP.Data.Tests.Migrations;

[TestFixture]
public class MigrationFilesTests
{
    private const string AutoGeneratedHeader = "// <auto-generated />";

    [Test]
    public void MigrationFiles_Always_AreMarkedAsGeneratedCode()
    {
        string migrationsDirectory = Path.Combine(FindRepositoryRoot(), "source", "WaveMP.Data", "Migrations");

        string[] files = Directory.GetFiles(migrationsDirectory, "*.cs");

        files.Should().NotBeEmpty();
        files.Should().AllSatisfy(file => File.ReadLines(file).First().Should().Be(
            AutoGeneratedHeader,
            "migrations are generated code (dotnet ef migrations add) and must not be reformatted, see {0}",
            Path.GetFileName(file)));
    }

    private static string FindRepositoryRoot()
    {
        DirectoryInfo? directory = new(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "WaveMP.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName
            ?? throw new InvalidOperationException("The repository root (WaveMP.slnx) was not found.");
    }
}
